#!/usr/bin/env bash
# Writes deploy/k8s/overlays/release/kustomization.yaml, pinning every image to one commit.
#   usage: render-release.sh <base-overlay: ci|staging> <registry/owner> <tag>
#   e.g.   render-release.sh ci ghcr.io/acme 3f2c1d0
set -euo pipefail
overlay=${1:?overlay}
registry=${2:?registry, e.g. ghcr.io/owner}
tag=${3:?tag}
dir="$(cd "$(dirname "$0")" && pwd)/overlays/release"
mkdir -p "$dir"
{
  echo "# Generated by render-release.sh; do not edit."
  echo "apiVersion: kustomize.config.k8s.io/v1beta1"
  echo "kind: Kustomization"
  echo "resources:"
  echo "  - ../$overlay"
  echo "images:"
  for n in fleet-api ingest simulator web agent; do
    printf '  - name: satfleet/%s\n    newName: %s/satfleet-%s\n    newTag: "%s"\n' "$n" "$registry" "$n" "$tag"
  done
} > "$dir/kustomization.yaml"
echo "$dir"
