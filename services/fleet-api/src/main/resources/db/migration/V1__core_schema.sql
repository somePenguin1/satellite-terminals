-- Core relational model: commercial (plans, customers) and fleet (terminals, config, live status, alerts).

CREATE TABLE service_plans (
    code                text PRIMARY KEY,
    name                text        NOT NULL,
    family              text        NOT NULL CHECK (family IN ('residential', 'business', 'maritime')),
    tier                smallint    NOT NULL,
    downlink_mbps       integer     NOT NULL CHECK (downlink_mbps > 0),
    uplink_mbps         integer     NOT NULL CHECK (uplink_mbps > 0),
    monthly_price_cents integer     NOT NULL CHECK (monthly_price_cents >= 0),
    UNIQUE (family, tier)
);

CREATE TABLE customers (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text        NOT NULL,
    segment         text        NOT NULL CHECK (segment IN ('residential', 'business', 'maritime', 'enterprise', 'government')),
    region          text        NOT NULL,
    account_manager text        NOT NULL,
    contact_email   text,
    created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX customers_name_idx ON customers (lower(name));

CREATE SEQUENCE terminal_number_seq START 1;

CREATE TABLE terminals (
    id            text PRIMARY KEY CHECK (id ~ '^SAT-[0-9]{5,}$'),
    serial_number text             NOT NULL UNIQUE,
    customer_id   bigint           NOT NULL REFERENCES customers (id),
    plan_code     text             NOT NULL REFERENCES service_plans (code),
    model         text             NOT NULL,
    status        text             NOT NULL CHECK (status IN ('provisioned', 'active', 'suspended', 'decommissioned')),
    region        text             NOT NULL,
    latitude      double precision NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude     double precision NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    activated_at  timestamptz,
    created_at    timestamptz      NOT NULL DEFAULT now(),
    updated_at    timestamptz      NOT NULL DEFAULT now()
);
CREATE INDEX terminals_customer_idx ON terminals (customer_id);
CREATE INDEX terminals_status_idx ON terminals (status);
CREATE INDEX terminals_region_idx ON terminals (region);

-- Desired device configuration. `version` drives optimistic concurrency (HTTP ETag / If-Match).
CREATE TABLE terminal_configs (
    terminal_id              text PRIMARY KEY REFERENCES terminals (id) ON DELETE CASCADE,
    version                  integer     NOT NULL DEFAULT 1,
    report_interval_ms       integer     NOT NULL DEFAULT 5000 CHECK (report_interval_ms BETWEEN 1000 AND 300000),
    telemetry_level          text        NOT NULL DEFAULT 'basic' CHECK (telemetry_level IN ('basic', 'detailed')),
    band                     text        NOT NULL DEFAULT 'Ku' CHECK (band IN ('Ku', 'Ka')),
    tx_power_dbm             real        NOT NULL DEFAULT 27 CHECK (tx_power_dbm BETWEEN 10 AND 33),
    qos_profile              text        NOT NULL DEFAULT 'standard' CHECK (qos_profile IN ('standard', 'priority', 'business-critical')),
    firmware_channel         text        NOT NULL DEFAULT 'stable' CHECK (firmware_channel IN ('stable', 'beta')),
    maintenance_window_start time        NOT NULL DEFAULT '02:00',
    maintenance_window_end   time        NOT NULL DEFAULT '04:00',
    updated_at               timestamptz NOT NULL DEFAULT now(),
    updated_by               text        NOT NULL DEFAULT 'system'
);

CREATE TABLE terminal_config_history (
    terminal_id text        NOT NULL REFERENCES terminals (id) ON DELETE CASCADE,
    version     integer     NOT NULL,
    config      jsonb       NOT NULL,
    changed_by  text        NOT NULL,
    changed_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (terminal_id, version)
);

-- Every committed config version is captured, whichever code path wrote it.
CREATE FUNCTION record_config_history() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    INSERT INTO terminal_config_history (terminal_id, version, config, changed_by, changed_at)
    VALUES (NEW.terminal_id, NEW.version,
            to_jsonb(NEW) - 'terminal_id' - 'version' - 'updated_at' - 'updated_by',
            NEW.updated_by, NEW.updated_at);
    RETURN NEW;
END
$$;

CREATE TRIGGER terminal_configs_history
    AFTER INSERT OR UPDATE ON terminal_configs
    FOR EACH ROW EXECUTE FUNCTION record_config_history();

-- Latest sample per terminal, upserted by the ingest service on every batch.
-- Low fillfactor leaves room for HOT updates on this very update-heavy table.
CREATE TABLE terminal_status (
    terminal_id      text PRIMARY KEY REFERENCES terminals (id) ON DELETE CASCADE,
    last_seen_at     timestamptz NOT NULL,
    last_seq         bigint      NOT NULL,
    link_state       smallint    NOT NULL,
    latency_ms       real,
    jitter_ms        real,
    packet_loss_pct  real,
    downlink_mbps    real,
    uplink_mbps      real,
    snr_db           real,
    obstruction_pct  real,
    firmware_version text,
    transport        text        NOT NULL,
    updated_at       timestamptz NOT NULL DEFAULT now()
) WITH (fillfactor = 70);

CREATE TABLE alerts (
    id               bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    terminal_id      text        NOT NULL REFERENCES terminals (id) ON DELETE CASCADE,
    kind             text        NOT NULL,
    severity         text        NOT NULL CHECK (severity IN ('critical', 'warning')),
    message          text        NOT NULL,
    observed_value   double precision,
    opened_at        timestamptz NOT NULL DEFAULT now(),
    last_observed_at timestamptz NOT NULL DEFAULT now(),
    acknowledged_at  timestamptz,
    acknowledged_by  text,
    ack_note         text,
    resolved_at      timestamptz
);
-- At most one open alert of each kind per terminal; the evaluator relies on this for idempotent upserts.
CREATE UNIQUE INDEX alerts_one_open_per_kind ON alerts (terminal_id, kind) WHERE resolved_at IS NULL;
CREATE INDEX alerts_open_idx ON alerts (opened_at DESC) WHERE resolved_at IS NULL;
CREATE INDEX alerts_terminal_idx ON alerts (terminal_id, opened_at DESC);
